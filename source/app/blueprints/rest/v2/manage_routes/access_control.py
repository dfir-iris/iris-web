@access_control_blueprint.get('/schema')
@ac_api_requires(Permissions.server_administrator)
def get_access_control_schema() -> Response:
    """Enum metadata for the Access Control editor.

    Permissions are exposed as a flat list of `{name, value, label,
    description}` ordered by their bit value — that's the order the
    editor renders the checklist. CaseAccessLevel is shipped the
    same way but as a small mutually-exclusive set the UI renders as
    a select.
    """
    perms = []
    for perm in sorted(Permissions, key=lambda p: p.value):
        meta = _PERMISSION_LABELS.get(perm.name, {})
        perms.append({
            'name': perm.name,
            'value': perm.value,
            'label': meta.get('label', perm.name.replace('_', ' ').capitalize()),
            'description': meta.get('description', ''),
        })

    access_levels = []
    for level in sorted(CaseAccessLevel, key=lambda l: l.value):
        meta = _CASE_ACCESS_LABELS.get(level.name, {})
        access_levels.append({
            'name': level.name,
            'value': level.value,
            'label': meta.get('label', level.name.replace('_', ' ').capitalize()),
            'description': meta.get('description', ''),
        })

    return response_api_success({
        'permissions': perms,
        'case_access_levels': access_levels,
    })


@access_control_blueprint.get('/accessible-cases')
@ac_api_requires(Permissions.server_administrator)
def list_accessible_cases() -> Response:
    """Lightweight case picker for the per-user / per-group case-access
    modals.

    Returns at most 200 rows ordered by `case_id DESC`, optionally
    filtered by a `search` ILIKE on case name + SOC id. Each
    candidate is re-checked with `ac_fast_check_current_user_has_case_access`
    so an admin who's explicitly removed themselves from a case
    still doesn't see it in the picker.
    """
    from sqlalchemy import or_
    query = Cases.query.with_entities(Cases.case_id, Cases.name, Cases.soc_id)
    search = (request.args.get('search') or '').strip() or None
    if search:
        needle = f'%{search}%'
        query = query.filter(or_(Cases.name.ilike(needle), Cases.soc_id.ilike(needle)))
    query = query.order_by(Cases.case_id.desc()).limit(200)

    items: List[Dict[str, Any]] = []
    for row in query.all():
        if not ac_fast_check_current_user_has_case_access(
            row.case_id, [CaseAccessLevel.read_only, CaseAccessLevel.full_access]
        ):
            continue
        items.append({
            'case_id': row.case_id,
            'name': row.name,
            'soc_id': row.soc_id,
        })

    return response_api_success({'data': items})


@access_control_blueprint.post('/recompute-all')
@ac_api_requires(Permissions.server_administrator)
def recompute_all_users_access() -> Response:
    """Rebuild the effective-access cache for every user.

    Expensive on large fleets — the legacy UI gated this behind a
    confirmation. The page does the same client-side; the endpoint
    itself just runs the helper synchronously.
    """
    ac_recompute_all_users_effective_ac()
    return response_api_success({'message': 'Recomputed effective access for all users'})
