"""v2 endpoints supporting the Access Control admin page.

Two small concerns:

  * `GET /schema` — exposes the `Permissions` (bitmask) and
    `CaseAccessLevel` enums + their canonical labels. The frontend
    renders the permission editor + the case-access dropdown
    directly from this so adding a new permission bit or access
    level only needs a backend change.
  * `GET /accessible-cases` — server-side scoped case picker for
    the per-user / per-group case-access modals. Returns at most
    200 rows, ordered newest-first, filtered by an optional `search`
    ILIKE on case name + SOC id. Each row is re-checked against the
    current user's case ACL — even though the page is admin-gated,
    an admin who's removed themselves from a case still doesn't see
    it.
  * `POST /recompute-all` — wrapper around the existing
    `ac_recompute_all_users_effective_ac()` helper so admins can
    rebuild the effective-access cache from the UI after a manual
    DB poke.
"""

